// Writes lib/db-types.ts from the real database schema, in the same shape `supabase gen types`
// produces, so the app's queries can be checked against the tables. It reads a Postgres that has had
// every migration applied (scripts/test-db.sh builds one: crm_test). Run it after adding a migration:
//
//   DATABASE_URL=postgres://postgres:postgres@localhost:5432/crm_test node scripts/gen-db-types.mjs
//   node scripts/gen-db-types.mjs --check    (exits 1 if lib/db-types.ts is out of date; used in CI)
//
// Needs the psql client. Point it at a local or CI database, never at a real project.
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("Set DATABASE_URL to a local Postgres that has had every migration applied.");
  process.exit(1);
}
const OUT = "lib/db-types.ts";
const check = process.argv.includes("--check");

const sql = `
select c.table_name, c.column_name, c.udt_name, c.is_nullable,
       (c.column_default is not null or c.is_identity = 'YES' or c.is_generated = 'ALWAYS') as has_default
  from information_schema.columns c
  join information_schema.tables t using (table_schema, table_name)
 where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
 order by c.table_name, c.ordinal_position`;
const rows = execFileSync("psql", [url, "-qtA", "-F", "|", "-c", sql], { encoding: "utf8" })
  .trim()
  .split("\n")
  .filter(Boolean)
  .map((l) => {
    const [table, column, udt, nullable, hasDefault] = l.split("|");
    return { table, column, udt, nullable: nullable === "YES", hasDefault: hasDefault === "t" };
  });

// PostgREST sends numeric and bigint as JSON numbers.
const TS = {
  uuid: "string", text: "string", varchar: "string", bpchar: "string", citext: "string",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number",
  bool: "boolean", timestamptz: "string", timestamp: "string", date: "string", time: "string",
  json: "Json", jsonb: "Json",
};
function tsType(udt) {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  if (!(udt in TS)) throw new Error(`Unmapped column type "${udt}". Add it to TS in scripts/gen-db-types.mjs.`);
  return TS[udt];
}

// Foreign keys, so embedded selects such as leads(name) type-check.
const fkSql = `
select c.conrelid::regclass::text, c.conname, a.attname, c.confrelid::regclass::text, fa.attname,
       exists (select 1 from pg_index i where i.indrelid = c.conrelid and i.indisunique and i.indkey::int2[] = c.conkey) as one_to_one
  from pg_constraint c
  join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
  join pg_attribute fa on fa.attrelid = c.confrelid and fa.attnum = c.confkey[1]
 where c.contype = 'f' and c.connamespace = 'public'::regnamespace and array_length(c.conkey, 1) = 1
 order by 1, 2`;
const fks = execFileSync("psql", [url, "-qtA", "-F", "|", "-c", fkSql], { encoding: "utf8" })
  .trim()
  .split("\n")
  .filter(Boolean)
  .map((l) => {
    const [table, name, column, refTable, refColumn, one] = l.split("|");
    return { table: table.replace(/^public\./, ""), name, column, refTable: refTable.replace(/^public\./, ""), refColumn, one: one === "t" };
  });

const tables = new Map();
for (const r of rows) {
  if (!tables.has(r.table)) tables.set(r.table, []);
  tables.get(r.table).push(r);
}

const lines = [];
const push = (s = "") => lines.push(s);
push("// GENERATED by scripts/gen-db-types.mjs from the migrations. Do not edit by hand.");
push("// Regenerate after adding a migration; CI fails if this file is out of date.");
push();
push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
push();
push("export type Database = {");
push("  public: {");
push("    Tables: {");
for (const [name, cols] of tables) {
  push(`      ${name}: {`);
  for (const kind of ["Row", "Insert", "Update"]) {
    push(`        ${kind}: {`);
    for (const c of cols) {
      const base = tsType(c.udt);
      const type = c.nullable ? `${base} | null` : base;
      const optional = kind === "Update" || (kind === "Insert" && (c.hasDefault || c.nullable));
      push(`          ${c.column}${optional ? "?" : ""}: ${type};`);
    }
    push("        };");
  }
  const rels = fks.filter((f) => f.table === name);
  if (rels.length === 0) push("        Relationships: [];");
  else {
    push("        Relationships: [");
    for (const f of rels) {
      push("          {");
      push(`            foreignKeyName: "${f.name}";`);
      push(`            columns: ["${f.column}"];`);
      push(`            isOneToOne: ${f.one};`);
      push(`            referencedRelation: "${f.refTable}";`);
      push(`            referencedColumns: ["${f.refColumn}"];`);
      push("          },");
    }
    push("        ];");
  }
  push("      };");
}
push("    };");
push("    Views: { [_ in never]: never };");
push("    Functions: {");
push("      claim_inbound_jobs: {");
push("        Args: { p_limit?: number; p_lease_seconds?: number; p_max_attempts?: number };");
push('        Returns: Database["public"]["Tables"]["inbound_jobs"]["Row"][];');
push("      };");
push("      last_messages: {");
push("        Args: { p_business_id: string };");
push("        Returns: { lead_id: string; direction: string; body: string | null; sent_at: string; source: string | null }[];");
push("      };");
push("      search_leads_by_message: {");
push("        Args: { p_query: string; p_limit?: number };");
push("        Returns: { lead_id: string }[];");
push("      };");
push("      dashboard_stats: {");
push("        Args: { p_today_start: string; p_tomorrow_start: string; p_now?: string };");
push("        Returns: Json;");
push("      };");
push("    };");
push("    Enums: { [_ in never]: never };");
push("    CompositeTypes: { [_ in never]: never };");
push("  };");
push("};");
push();
push('type PublicSchema = Database["public"];');
push("export type Tables<T extends keyof PublicSchema[\"Tables\"]> = PublicSchema[\"Tables\"][T][\"Row\"];");
push("export type TablesInsert<T extends keyof PublicSchema[\"Tables\"]> = PublicSchema[\"Tables\"][T][\"Insert\"];");
push("export type TablesUpdate<T extends keyof PublicSchema[\"Tables\"]> = PublicSchema[\"Tables\"][T][\"Update\"];");

const out = lines.join("\n") + "\n";
if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== out) {
    console.error(`${OUT} is out of date. Run: DATABASE_URL=... node scripts/gen-db-types.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  fs.writeFileSync(OUT, out);
  console.log(`Wrote ${OUT} (${tables.size} tables).`);
}
